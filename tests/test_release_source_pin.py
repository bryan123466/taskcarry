"""Real synthetic Git objects freeze exact release bytes without building wheels."""
import os
from pathlib import Path
import subprocess
import tempfile
import unittest
from unittest import mock

from scripts import build_trial as release


class ReleaseSourcePinTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory(prefix='taskcarry-source-pin-')
        self.root = Path(self.temporary.name)
        self.repo = self.root / 'repo'
        self.repo.mkdir()
        self.patch = mock.patch.object(release, 'ROOT', self.repo)
        self.patch.start()
        self.addCleanup(self.patch.stop)
        self.environment = {key: value for key, value in os.environ.items() if not key.startswith('GIT_')}
        self.environment.update(GIT_CONFIG_NOSYSTEM='1', GIT_CONFIG_GLOBAL=str(self.root / 'no-global-config'))
        self.git('init', '--quiet', '-b', 'synthetic-release')
        self.git('config', 'user.name', 'Synthetic Release')
        self.git('config', 'user.email', 'synthetic@example.invalid')
        self.git('config', 'core.autocrlf', 'false')
        names = release.REQUIRED | {'START_HERE.md', '.gitattributes', 'taskcarry/__init__.py'}
        names |= {'skills/' + skill + '/SKILL.md' for skill in release.SKILLS}
        names |= {'docs/' + lang + '/' + guide + '.md' for lang in ('en', 'zh-CN', 'zh-TW')
                  for guide in ('windows-example', 'updating')}
        for name in names:
            path = self.repo / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(b'{}\n' if path.suffix == '.json' else b'Synthetic committed content\nSecond line\n')
        (self.repo / 'pyproject.toml').write_text('[project]\nversion = "' + release.__version__ + '"\n', encoding='utf-8')
        (self.repo / 'taskcarry/__init__.py').write_text('__version__ = "' + release.__version__ + '"\n', encoding='utf-8')
        (self.repo / '.gitattributes').write_bytes(b'*.md text eol=lf\n')
        entry = '[Download](https://github.com/bryan123466/taskcarry/releases/tag/v' + release.__version__ + ')\n'
        entry += ''.join('[Guide](docs/' + lang + '/' + name + '.md)\n'
                         for lang in ('en', 'zh-CN', 'zh-TW') for name in ('windows-example', 'updating'))
        (self.repo / 'START_HERE.md').write_text(entry, encoding='utf-8', newline='\n')
        self.git('add', '--', '.')
        self.git('commit', '--quiet', '-m', 'Synthetic reviewed source')
        self.commit = self.git('rev-parse', 'HEAD').decode().strip()

    def tearDown(self):
        self.temporary.cleanup()

    def git(self, *args):
        result = subprocess.run(['git', '-c', 'core.hooksPath=' + os.devnull, '-c', 'commit.gpgsign=false',
                                 '-C', str(self.repo), *args], env=self.environment,
                                capture_output=True, timeout=60)
        self.assertEqual(0, result.returncode, result.stderr.decode('utf-8', 'replace'))
        return result.stdout

    def test_crlf_checkout_freezes_lf_git_bytes_and_rebuilds_all_six_resources(self):
        for path in self.repo.rglob('*.md'):
            path.write_bytes(path.read_bytes().replace(b'\n', b'\r\n'))
        contents, _ = release.snapshot()
        self.assertIn(b'\r\n', contents['README.md'])
        generated = [name for name in contents if name.startswith('taskcarry/skill_data/')]
        self.assertEqual(6, len(generated))
        # Stale generated copies are never trusted as canonical release bytes.
        for name in generated:
            contents[name] = b'stale generated bytes\r\n'
        before = {'head': self.git('rev-parse', 'HEAD'), 'index': (self.repo / '.git/index').read_bytes(),
                  'files': {p.relative_to(self.repo).as_posix(): p.read_bytes()
                            for p in release.files()}}
        frozen = release.freeze_commit(contents, self.commit)
        for name, data in frozen.items():
            canonical = name.replace('taskcarry/skill_data/', 'skills/', 1) if name in generated else name
            self.assertEqual(self.git('show', self.commit + ':' + canonical), data, name)
        self.assertNotIn(b'\r\n', frozen['README.md'])
        self.assertEqual(before['head'], self.git('rev-parse', 'HEAD'))
        self.assertEqual(before['index'], (self.repo / '.git/index').read_bytes())
        self.assertEqual(before['files'], {p.relative_to(self.repo).as_posix(): p.read_bytes() for p in release.files()})
        actual, _ = release.snapshot(source_commit=self.commit)
        self.assertEqual(actual, frozen)

    def test_worktree_change_refuses_before_output_or_build_dependency_check(self):
        (self.repo / 'README.md').write_bytes(b'New unreviewed content\n')
        destination = self.root / 'uncreated-parent' / 'product'
        with mock.patch.object(release, 'build_dependencies', side_effect=AssertionError('should not build')):
            with self.assertRaisesRegex(RuntimeError, 'differs from reviewed commit'):
                release.build(destination, source_commit=self.commit)
        self.assertFalse(destination.parent.exists())
        self.assertEqual({'repo'}, {p.name for p in self.root.iterdir()})

    def test_membership_checks_both_deleted_and_untracked_allowed_paths(self):
        contents, _ = release.snapshot()
        missing = dict(contents)
        missing.pop('README.md')
        with self.assertRaisesRegex(RuntimeError, 'missing_from_checkout'):
            release.freeze_commit(missing, self.commit)
        extra = dict(contents, **{'docs/untracked-note.md': b'Unreviewed\n'})
        with self.assertRaisesRegex(RuntimeError, 'not_in_commit'):
            release.freeze_commit(extra, self.commit)

    def test_full_commit_required_and_caller_git_dir_cannot_redirect_object_reads(self):
        contents, _ = release.snapshot()
        with self.assertRaises(ValueError):
            release.freeze_commit(contents, self.commit[:12])
        tree = self.git('rev-parse', 'HEAD^{tree}').decode().strip()
        with self.assertRaisesRegex(RuntimeError, 'commit object'):
            release.freeze_commit(contents, tree)
        with mock.patch.dict(os.environ, {'GIT_DIR': str(self.root / 'wrong-repository'), 'GIT_INDEX_FILE': str(self.root / 'wrong-index')}):
            frozen = release.freeze_commit(contents, self.commit)
        self.assertEqual(contents, frozen)
        self.assertFalse((self.root / 'wrong-index').exists())

    def test_git_replace_cannot_change_the_named_commit_payload(self):
        original, _ = release.snapshot()
        (self.repo / 'README.md').write_bytes(b'Replacement content\n')
        self.git('add', '--', 'README.md')
        self.git('commit', '--quiet', '-m', 'Synthetic replacement object')
        replacement = self.git('rev-parse', 'HEAD').decode().strip()
        self.git('replace', self.commit, replacement)
        frozen = release.freeze_commit(original, self.commit)
        self.assertEqual(b'Synthetic committed content\nSecond line\n', frozen['README.md'])

    def test_generated_resource_membership_cannot_add_unreviewed_payload(self):
        contents, _ = release.snapshot()
        contents['taskcarry/skill_data/extra.md'] = b'Unexpected generated file\n'
        with self.assertRaisesRegex(RuntimeError, 'Generated skill membership'):
            release.freeze_commit(contents, self.commit)


if __name__ == '__main__':
    unittest.main()
